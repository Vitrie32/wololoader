#!/usr/bin/env python3
"""
Generates build/ui_files.h embedding all static files from scriptorium/ui/.
Each file is embedded as a static C array with a lookup table mapping URI paths
to their embedded data, length, and MIME Content-Type.
"""

import sys
import os

MIME_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".htm":  "text/html; charset=utf-8",
    ".css":  "text/css; charset=utf-8",
    ".js":   "application/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".png":  "image/png",
    ".jpg":  "image/jpeg",
    ".jpeg": "image/jpeg",
    ".gif":  "image/gif",
    ".svg":  "image/svg+xml",
    ".ico":  "image/x-icon",
    ".woff2": "font/woff2",
    ".woff":  "font/woff",
    ".ttf":   "font/ttf",
}

def get_content_type(filename):
    _, ext = os.path.splitext(filename.lower())
    return MIME_TYPES.get(ext, "application/octet-stream")

def main():
    if len(sys.argv) < 3:
        print(f"Usage: {sys.argv[0]} <ui_dir> <output_header> [--lib <name> <ext,ext,...>]")
        sys.exit(1)

    # --lib <name> <exts>: a second table (g_<name>_files, g_<name>_file_count) that only holds files
    # with those extensions and skips folders starting with "_" (e.g. icon_library/_src). It is
    # included after ui_files.h, so it reuses the UiFile type instead of declaring it again.
    lib = None
    exts = None
    if len(sys.argv) >= 6 and sys.argv[3] == "--lib":
        lib = sys.argv[4]
        exts = tuple(e.strip().lower() for e in sys.argv[5].split(","))

    ui_dir = os.path.abspath(sys.argv[1])
    out_path = os.path.abspath(sys.argv[2])
    os.makedirs(os.path.dirname(out_path), exist_ok=True)

    files = []
    if os.path.isdir(ui_dir):
        for root, dirs, filenames in os.walk(ui_dir):
            dirs[:] = sorted(d for d in dirs if not (lib and d.startswith("_")))
            for fn in sorted(filenames):
                if exts and not fn.lower().endswith(exts):
                    continue
                full_path = os.path.join(root, fn)
                rel_path = os.path.relpath(full_path, ui_dir).replace("\\", "/")
                if not rel_path.startswith("/"):
                    rel_path = "/" + rel_path
                files.append((rel_path, full_path))

    with open(out_path, "w", encoding="utf-8") as out:
        out.write("// Auto-generated by tools/gen_ui_files.py - do not edit manually\n")
        guard = "UI_FILES_H" if not lib else f"{lib.upper()}_FILES_H"
        pre = "ui" if not lib else lib
        out.write(f"#ifndef {guard}\n")
        out.write(f"#define {guard}\n\n")
        out.write("#include <stddef.h>\n\n")
        if not lib:
            out.write("typedef struct {\n")
            out.write("    const char *path;\n")
            out.write("    const unsigned char *data;\n")
            out.write("    size_t len;\n")
            out.write("    const char *content_type;\n")
            out.write("} UiFile;\n\n")

        for idx, (rel_path, full_path) in enumerate(files):
            with open(full_path, "rb") as f:
                data = f.read()
            out.write(f"// Embedded from {rel_path} ({len(data)} bytes)\n")
            out.write(f"static const unsigned char {pre}_data_{idx}[] = {{\n")
            # Write bytes in chunks of 16
            for i in range(0, len(data), 16):
                chunk = data[i:i+16]
                hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
                out.write(f"    {hex_bytes},\n")
            if len(data) == 0:
                out.write("    0x00\n")
            out.write("};\n\n")

        out.write(f"static const UiFile g_{pre}_files[] = {{\n")
        for idx, (rel_path, full_path) in enumerate(files):
            with open(full_path, "rb") as f:
                data_len = len(f.read())
            c_type = get_content_type(rel_path)
            out.write(f"    {{ \"{rel_path}\", {pre}_data_{idx}, {data_len}, \"{c_type}\" }},\n")
        if not files:
            out.write("    { \"/index.html\", NULL, 0, \"text/html; charset=utf-8\" }\n")
        out.write("};\n\n")

        count_expr = f"{len(files)}" if files else "0"
        out.write(f"static const size_t g_{pre}_file_count = {count_expr};\n\n")
        out.write(f"#endif // {guard}\n")

    print(f"Generated {out_path} with {len(files)} embedded file(s).")

if __name__ == "__main__":
    main()
